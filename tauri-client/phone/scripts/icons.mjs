// Writes src/line-icons.ts from the Android app's Line icons (Icons.kt and
// ShellIcons.kt), so both apps draw the same shapes. Run it again after
// either file changes: node tauri-client/phone/scripts/icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const ui = new URL('../../../android-native/app/src/main/java/com/mikerosoft/threadbear/android/ui/', import.meta.url);
const sources = ['Icons.kt', 'ShellIcons.kt'].map((f) => readFileSync(new URL(f, ui), 'utf8'));

// Kotlin's circle(cx, cy, r): the same arc path, numbers printed as Kotlin does.
const num = (n) => (Number.isInteger(n) ? `${n}.0` : String(n));
const circle = (cx, cy, r) => `M${num(cx - r)} ${num(cy)}a${num(r)} ${num(r)} 0 1 0 ${num(2 * r)} 0a${num(r)} ${num(r)} 0 1 0 ${num(-2 * r)} 0`;

const icons = {};
for (const source of sources) {
  // Each icon("name", …) call, which can run over several lines.
  for (const start of source.matchAll(/\bicon\("(\w+)",/g)) {
    const name = start[1];
    const from = start.index + start[0].length;
    let end = from;
    for (let depth = 1, inString = false; depth > 0; end++) {
      const c = source[end];
      if (c === '"') inString = !inString;
      else if (!inString && c === '(') depth++;
      else if (!inString && c === ')') depth--;
    }
    const args = source.slice(from, end - 1);
    const paths = [];
    let fill = false;
    for (const m of args.matchAll(/"([^"]*)"|circle\(([\d.]+)f,\s*([\d.]+)f,\s*([\d.]+)f\)|fill\s*=\s*true/g)) {
      if (m[1] !== undefined) paths.push(m[1]);
      else if (m[2] !== undefined) paths.push(circle(Number(m[2]), Number(m[3]), Number(m[4])));
      else fill = true;
    }
    if (icons[name]) throw new Error(`Two icons named ${name}`);
    icons[name] = { paths, fill };
  }
}

const body = Object.entries(icons)
  .map(([name, { paths, fill }]) => `  ${name}: { paths: ${JSON.stringify(paths)}, fill: ${fill} },`)
  .join('\n');
writeFileSync(
  new URL('../src/line-icons.ts', import.meta.url),
  `// Generated by scripts/icons.mjs from the Android app's Icons.kt and ShellIcons.kt. Don't edit.\nexport const LINE = {\n${body}\n} as const;\n\nexport type LineName = keyof typeof LINE;\n`,
);
console.log(`${Object.keys(icons).length} icons`);
